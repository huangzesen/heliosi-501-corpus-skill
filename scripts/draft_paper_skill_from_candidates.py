    lines.append(f"kind: {DRAFT_FRONTMATTER_KIND}")
    lines.append(f"promotion_status: {DRAFT_PROMOTION_STATUS}")
    lines.append("verified: false")
    lines.append(f"maturity: {DRAFT_MATURITY}")
    lines.append(f"quality_level: {DRAFT_QUALITY_LEVEL}")
    lines.append(f"executable_status: {DRAFT_EXECUTABLE_STATUS}")
    lines.append("authors_verified: false")
    lines.append("")
    lines.append("# Candidate-derived bibliographic provenance (UNVERIFIED).")
    lines.append("# Treat every value as an import from the discovery backend,")
    lines.append("# not a verified claim. The promotion_gate below records the")
    lines.append("# gates that must be cleared before any of this is treated as truth.")
    lines.append(f"title: {_yaml_str(title)}")
    lines.append(f"year: {_yaml_str(year)}")
    lines.append(f"doi: {_yaml_str(doi)}")
    lines.append(f"arxiv: {_yaml_str(arxiv_id)}")
    lines.append(f"ads_bibcode: {_yaml_str(bibcode)}")
    lines.append(f"url: {_yaml_str(url)}")
    lines.append("authors:" + _yaml_list(authors))
    lines.append("topic_tags:" + _yaml_list(topic_tags))
    lines.append("")
    lines.append("# Discovery provenance (which discovery run produced this candidate).")
    lines.append("discovery:")
    lines.append(f"  source: {_yaml_str(source)}")
    lines.append(f"  backend: {_yaml_str(source)}")
    lines.append(f"  query: {_yaml_str(query)}")
    lines.append(f"  discovered_at_utc: {_yaml_str(discovered_at)}")
    lines.append(f"  dedupe_id: {_yaml_str(dedupe_id)}")
    lines.append(f"  corpus_status: {_yaml_str(corpus_status)}")
    lines.append(f"  corpus_match_via: {_yaml_str(corpus_match_via)}")
    lines.append(
        "  corpus_match_slugs:" + _yaml_list(list(corpus_match_slugs))
    )
    lines.append(
        "  corpus_match_titles:" + _yaml_list(list(corpus_match_titles))
    )
    lines.append("")
    lines.append("# Promotion gate. Every item must be flipped to true (by a")
    lines.append("# downstream human/agent evidence review) before this draft can")
    lines.append("# be considered for promotion into references/corpus/.")
    lines.append("promotion_gate:")
    for key in PROMOTION_GATE_KEYS:
        lines.append(f"  {key}: false")
    lines.append("")
    return "\n".join(lines)


