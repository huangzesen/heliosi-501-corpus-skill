EPILOG = """\
Examples:
  # Draft only new_candidate rows from a JSONL emitted by discovery:
  python3 scripts/draft_paper_skill_from_candidates.py \\
      --from-candidates /tmp/cand.jsonl --drafts-dir /tmp/drafts

  # Read from a run bundle (--run-dir output of the discovery script):
  python3 scripts/draft_paper_skill_from_candidates.py \\
      --from-run-dir /tmp/discovery-run-2026-05-19 \\
      --drafts-dir /tmp/drafts

  # Also draft unjoined rows (novelty join disabled at discovery time):
  python3 scripts/draft_paper_skill_from_candidates.py \\
      --from-candidates /tmp/cand.jsonl --drafts-dir /tmp/drafts \\
      --include-unjoined

Drafts are NOT corpus entries. They live in the --drafts-dir you pick;
they are never written under references/corpus/. Read the per-draft
metadata.yaml::promotion_gate before promoting anything.
"""


def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="draft_paper_skill_from_candidates.py",
        description=(
            "Generate quarantined draft paper-skill scaffolds from "
            "discovery candidate records. Drafts live OUTSIDE "
            "references/corpus/ and must not be promoted without "
            "completing the per-draft promotion gate."
        ),
        epilog=EPILOG,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        "--drafts-dir", required=True,
        help="Directory to write drafts into. Must not be inside "
             "references/corpus/.",
    )
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument(
        "--from-candidates",
        help="Path to a candidate JSONL emitted by "
             "scripts/discover_heliophysics_literature.py.",
    )
    src.add_argument(
        "--from-run-dir",
        help="Path to a discovery run-bundle directory "
             "(reads <run-dir>/candidates.jsonl).",
    )
    p.add_argument(
        "--include-unjoined", action="store_true",
        help="Also draft rows with corpus_status='unjoined'. Off by default.",
    )
    p.add_argument(
        "--include-all-statuses", action="store_true",
        help="Also draft rows with corpus_status='already_curated'. "
             "Off by default; loud opt-in.",
    )
    p.add_argument(
        "--overwrite", action="store_true",
        help="Allow re-writing existing draft directories under "
             "--drafts-dir. Off by default; the script never silently "
             "clobbers prior drafts.",
    )
    p.add_argument(
        "--quiet", action="store_true",
        help="Suppress the human-readable stderr summary.",
    )
    p.add_argument(
        "--version", action="version",
        version=f"draft_paper_skill_from_candidates {__version__}",
    )
    return p


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = _build_parser().parse_args(argv)

    drafts_dir = Path(args.drafts_dir)
    _refuse_if_inside_corpus(drafts_dir)

    if args.from_candidates:
        input_kind = "candidates-jsonl"
        input_path = Path(args.from_candidates)
        records = load_candidates(input_path)
    else:
        input_kind = "run-bundle"
        input_path = Path(args.from_run_dir)
        records = load_candidates_from_run_dir(input_path)

    selected, skipped = select_candidates(
        records,
        include_unjoined=bool(args.include_unjoined),
        include_all_statuses=bool(args.include_all_statuses),
    )

    draft_summaries = write_drafts(
        selected, drafts_dir, overwrite=bool(args.overwrite)
    )

    manifest = build_manifest(
        input_kind=input_kind,
        input_path=input_path,
        selected=selected,
        skipped=skipped,
        draft_summaries=draft_summaries,
        cli_args={
            "drafts_dir": str(drafts_dir),
            "from_candidates": args.from_candidates,
            "from_run_dir": args.from_run_dir,
            "include_unjoined": bool(args.include_unjoined),
            "include_all_statuses": bool(args.include_all_statuses),
            "overwrite": bool(args.overwrite),
        },
    )

    manifest_path = drafts_dir / MANIFEST_FILENAME
    report_path = drafts_dir / REPORT_FILENAME
    with manifest_path.open("w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2, sort_keys=False)
        f.write("\n")
    report_path.write_text(render_report(manifest), encoding="utf-8")

    if not args.quiet:
        sys.stderr.write(
            f"draft_paper_skill_from_candidates: wrote "
            f"{len(draft_summaries)} draft(s) under {drafts_dir} "
            f"(skipped {len(skipped)}); manifest={manifest_path}\n"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
