_AUTHOR_SUFFIX_RE = re.compile(r"\b(jr|sr|iii|ii|iv)\b\.?", re.IGNORECASE)
_NON_SLUG_RE = re.compile(r"[^a-z0-9]+")


def _fold(s: str) -> str:
    if not s:
        return ""
    nfkd = unicodedata.normalize("NFKD", s)
    no_marks = "".join(c for c in nfkd if not unicodedata.combining(c))
    return no_marks.lower()


def _author_slug(authors: Optional[Sequence[str]]) -> str:
    if not authors:
        return "anon"
    raw = (authors[0] or "").strip()
    if not raw:
        return "anon"
    raw = _AUTHOR_SUFFIX_RE.sub("", raw).strip()
    tokens = [t for t in re.split(r"\s+", raw) if t and not t.endswith(".")]
    surname = tokens[-1] if tokens else raw
    folded = _fold(surname)
    cleaned = _NON_SLUG_RE.sub("-", folded).strip("-")
    return cleaned or "anon"


def _title_slug(title: Optional[str], *, max_words: int = 6) -> str:
    if not title:
        return "untitled"
    folded = _fold(title)
    cleaned = _NON_SLUG_RE.sub("-", folded).strip("-")
    parts = [p for p in cleaned.split("-") if p]
    if not parts:
        return "untitled"
    return "-".join(parts[:max_words])


def _id_hash(record: Dict) -> str:
    seed = record.get("id") or json.dumps(record, sort_keys=True, default=str)
    return hashlib.sha1(seed.encode("utf-8")).hexdigest()[:6]


def generate_slug(record: Dict) -> str:
    """Deterministic, filesystem-safe, collision-aware draft slug.

    Shape: ``draft__<author>__<year>__<title>__<hash6>``. The ``draft__``
    prefix is the headline visual quarantine marker; the hash suffix is
    derived from the candidate ``id`` (the discovery dedupe key) so two
    candidates that happen to share author + year + title still produce
    distinct slugs.
    """
    author = _author_slug(record.get("authors"))
    year = record.get("year")
    year_str = str(year) if year is not None else "noyear"
    title = _title_slug(record.get("title"))
    suffix = _id_hash(record)
    return f"{DRAFT_DIR_PREFIX}{author}__{year_str}__{title}__{suffix}"


