DRAFT_FRONTMATTER_KIND = "discovery-draft"
DRAFT_PROMOTION_STATUS = "unreviewed"
DRAFT_MATURITY = "candidate"
DRAFT_QUALITY_LEVEL = "unverified-candidate"
DRAFT_EXECUTABLE_STATUS = "unverified-draft"

DEFAULT_SELECTED_STATUSES: Tuple[str, ...] = ("new_candidate",)
KNOWN_STATUSES: Tuple[str, ...] = (
    "new_candidate",
    "unjoined",
    "already_curated",
)

