def load_candidates(path: Path) -> List[Dict]:
    """Load candidate records from a JSONL file. Comments/blank lines ignored."""
    out: List[Dict] = []
    with path.open("r", encoding="utf-8") as f:
        for line_no, raw in enumerate(f, start=1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise SystemExit(
                    f"draft_paper_skill_from_candidates: bad JSONL line "
                    f"{path}:{line_no}: {e}"
                ) from None
    return out


def load_candidates_from_run_dir(run_dir: Path) -> List[Dict]:
    """Read ``<run_dir>/candidates.jsonl`` (the discovery run-bundle layout)."""
    candidates_path = run_dir / "candidates.jsonl"
    if not candidates_path.is_file():
        raise SystemExit(
            f"draft_paper_skill_from_candidates: run-dir is missing "
            f"candidates.jsonl: {candidates_path}"
        )
    return load_candidates(candidates_path)


