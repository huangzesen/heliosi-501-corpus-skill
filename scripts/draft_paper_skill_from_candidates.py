#!/usr/bin/env python3
"""Draft *quarantined* paper-skill scaffolds from discovery candidates.

This is the second concrete increment of HelioSI's open-ended literature
pipeline (the first is ``scripts/discover_heliophysics_literature.py``).
The discovery script emits a JSONL stream of candidate records; this
script turns selected candidates into **draft** paper-skill directories
that live OUTSIDE ``references/corpus/`` and that read as unmistakably
unverified.

Quarantine model (load-bearing)
-------------------------------
A draft produced by this script is **not** a corpus entry. It is a
non-authoritative scaffold whose only authoritative content is the
candidate metadata + abstract that the discovery backend returned. Every
draft carries quarantine markers on multiple surfaces so that a human or
agent reader cannot mistake it for a curated 501-entry paper-skill:

  - directory name prefix ``draft__`` (visible in any file listing),
  - YAML frontmatter fields ``kind: discovery-draft``,
    ``promotion_status: unreviewed``, ``verified: false``,
    ``maturity: candidate``, ``quality_level: unverified-candidate``,
    ``executable_status: unverified-draft``, ``authors_verified: false``,
  - a DRAFT / UNVERIFIED / NOT A CORPUS ENTRY banner at the top of
    ``SKILL.md`` that explicitly disclaims promotion,
  - a ``promotion_gate:`` checklist in ``metadata.yaml`` whose every
    item is ``false`` until a downstream human/agent flips it after the
    relevant evidence work,
  - an aggregate ``draft_manifest.json`` + ``draft_report.md`` at the
    drafts-dir root that also carry the quarantine banner.

The script refuses to write anywhere under ``references/corpus/`` so a
user cannot accidentally pour drafts into the curated bundle.

CLI
---
Two input modes, mutually exclusive:

  - ``--from-candidates PATH`` reads a JSONL written by
    ``discover_heliophysics_literature.py``.
  - ``--from-run-dir PATH`` reads ``PATH/candidates.jsonl`` (the run
    bundle written by the discovery script's ``--run-dir``).

By default only candidates with ``corpus_status == "new_candidate"`` are
drafted. Opt-in:

  - ``--include-unjoined``     also draft ``unjoined`` rows (no manifest
                                join performed).
  - ``--include-all-statuses`` also draft ``already_curated`` rows.
                                (Loud opt-in; the default behaviour is
                                to never draft something that already
                                exists in the curated corpus.)

The drafts-dir must be empty / non-existent unless ``--overwrite`` is
passed. Existing per-candidate draft directories are also refused
without ``--overwrite``.

Testing
-------
Companion tests under
``tests/test_draft_paper_skill_from_candidates.py`` pin the quarantine
contract: defaults, slug shape, frontmatter fields, body banner,
manifest counts, run-bundle input, collision behaviour, and the
"no drafts inside references/corpus/" rail.
"""

