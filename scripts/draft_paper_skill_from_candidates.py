def build_manifest(
    *,
    input_kind: str,
    input_path: Path,
    selected: Sequence[Dict],
    skipped: Sequence[Dict],
    draft_summaries: Sequence[Dict],
    cli_args: Dict,
) -> Dict:
    return {
        "schema_version": MANIFEST_SCHEMA_VERSION,
        "script_version": __version__,
        "input_kind": input_kind,
        "input_path": str(input_path),
        "cli_args": dict(cli_args),
        "selected_count": len(selected),
        "skipped_count": len(skipped),
        "selected_counts_by_corpus_status": _counts_by_status(selected),
        "skipped_counts_by_corpus_status": _counts_by_status(skipped),
        "promotion_gate_keys": list(PROMOTION_GATE_KEYS),
        "drafts": list(draft_summaries),
        "quarantine_disclosure": (
            "Every entry under `drafts[]` is a non-authoritative draft "
            "scaffold. Drafts must not be promoted to references/corpus/ "
            "or cited as verified sources until the per-draft "
            "promotion_gate in metadata.yaml has been completed by a "
            "downstream evidence review."
        ),
        "limits": (
            "This manifest records only what this single invocation drafted "
            "from the supplied input. It does not assert that the inputs "
            "themselves are exhaustive, novel, or correctly classified."
        ),
    }


def render_report(manifest: Dict) -> str:
    lines: List[str] = []
    lines.append("# Draft paper-skill scaffold report")
    lines.append("")
    lines.append("> **DRAFT — UNVERIFIED — NOT PROMOTED**")
    lines.append(">")
    lines.append(
        "> The artifacts listed below are non-authoritative discovery-draft "
        "scaffolds. They are not corpus entries and must not be cited as "
        "verified sources until the promotion gate in each draft's "
        "`metadata.yaml` has been completed."
    )
    lines.append("")
    lines.append(f"- **Script version:** {manifest.get('script_version')}")
    lines.append(f"- **Manifest schema:** {manifest.get('schema_version')}")
    lines.append(f"- **Input kind:** {manifest.get('input_kind')}")
    lines.append(f"- **Input path:** `{manifest.get('input_path')}`")
    lines.append("")
    lines.append("## Selected counts")
    lines.append("")
    lines.append(f"- Total selected: **{manifest.get('selected_count', 0)}**")
    for status, count in sorted(
        (manifest.get("selected_counts_by_corpus_status") or {}).items()
    ):
        lines.append(f"  - `{status}`: {count}")
    lines.append("")
    lines.append("## Skipped counts")
    lines.append("")
    lines.append(f"- Total skipped: **{manifest.get('skipped_count', 0)}**")
    for status, count in sorted(
        (manifest.get("skipped_counts_by_corpus_status") or {}).items()
    ):
        lines.append(f"  - `{status}`: {count}")
    lines.append("")
    lines.append("## Draft directories")
    lines.append("")
    drafts = manifest.get("drafts") or []
    for d in drafts:
        lines.append(
            f"- `{d.get('path')}` — corpus_status=`{d.get('corpus_status')}` "
            f"— dedupe_id=`{d.get('dedupe_id')}`"
        )
    if not drafts:
        lines.append("- (no drafts written)")
    lines.append("")
    lines.append("## Promotion gate (every item must be cleared per draft)")
    lines.append("")
    for key in manifest.get("promotion_gate_keys") or []:
        lines.append(f"- `{key}`")
    lines.append("")
    lines.append("## Limits (honest framing)")
    lines.append("")
    lines.append(
        manifest.get("quarantine_disclosure")
        or "Drafts are non-authoritative quarantine artifacts."
    )
    lines.append("")
    lines.append(manifest.get("limits") or "")
    lines.append("")
    return "\n".join(lines)


