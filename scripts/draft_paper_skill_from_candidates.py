def select_candidates(
    records: Sequence[Dict],
    *,
    include_unjoined: bool = False,
    include_all_statuses: bool = False,
) -> Tuple[List[Dict], List[Dict]]:
    """Split records into (selected, skipped).

    Defaults: only ``corpus_status == "new_candidate"`` is selected.
    Records without a ``corpus_status`` are treated as ``unjoined``.
    ``--include-all-statuses`` is the only switch that admits
    ``already_curated`` rows.
    """
    allowed = set(DEFAULT_SELECTED_STATUSES)
    if include_unjoined:
        allowed.add("unjoined")
    if include_all_statuses:
        allowed.update(KNOWN_STATUSES)

    selected: List[Dict] = []
    skipped: List[Dict] = []
    for rec in records:
        status = rec.get("corpus_status") or "unjoined"
        if status in allowed:
            selected.append(rec)
        else:
            skipped.append(rec)
    return selected, skipped


def _counts_by_status(records: Sequence[Dict]) -> Dict[str, int]:
    counts: Dict[str, int] = {}
    for rec in records:
        status = rec.get("corpus_status") or "unjoined"
        counts[status] = counts.get(status, 0) + 1
    return counts


