def _format_authors_list(authors: Optional[Sequence[str]]) -> List[str]:
    if not authors:
        return []
    return [str(a).strip() for a in authors if str(a).strip()]


_YAML_RESERVED = {"null", "true", "false", "yes", "no", "~", "on", "off"}


def _yaml_str(value) -> str:
    """Render a scalar for YAML output. Quoted when ambiguous."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    s = str(value)
    if s == "":
        return '""'
    needs_quote = (
        any(c in s for c in ":#\n\"'")
        or s != s.strip()
        or s.lower() in _YAML_RESERVED
    )
    if not needs_quote:
        return s
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _yaml_list(values: Sequence[str], indent: str = "  ") -> str:
    if not values:
        return " []"
    lines = [""]
    for v in values:
        lines.append(f"{indent}- {_yaml_str(v)}")
    return "\n".join(lines)


def render_skill_md(record: Dict, *, slug: str) -> str:
    """Render the draft SKILL.md body."""
    title = record.get("title") or "(untitled candidate)"
    year = record.get("year")
    doi = record.get("doi")
    arxiv_id = record.get("arxiv_id")
    bibcode = record.get("bibcode")
    url = record.get("url")
    source = record.get("source")
    query = record.get("query")
    discovered_at = record.get("discovered_at_utc")
    abstract = record.get("abstract")
    topic_tags = record.get("topic_tags") or []
    authors = _format_authors_list(record.get("authors"))
    corpus_status = record.get("corpus_status") or "unjoined"
    dedupe_id = record.get("id")

    fm_lines = [
        "---",
        f"name: {slug}",
        f"kind: {DRAFT_FRONTMATTER_KIND}",
        f"promotion_status: {DRAFT_PROMOTION_STATUS}",
        "verified: false",
        f"maturity: {DRAFT_MATURITY}",
        f"quality_level: {DRAFT_QUALITY_LEVEL}",
        f"executable_status: {DRAFT_EXECUTABLE_STATUS}",
        "authors_verified: false",
        f"source_corpus_status: {corpus_status}",
        "---",
    ]
    frontmatter = "\n".join(fm_lines)

    prov_lines = [
        f"- **Title (candidate, unverified):** {title}",
        f"- **Year (candidate, unverified):** "
        f"{year if year is not None else 'TODO_verify'}",
        f"- **DOI:** {doi if doi else 'TODO_verify (not present in candidate)'}",
        f"- **arXiv:** {arxiv_id if arxiv_id else 'TODO_verify (not present in candidate)'}",
        f"- **ADS bibcode:** {bibcode if bibcode else 'TODO_verify (not present in candidate)'}",
        f"- **URL/source/backend:** {url or '(none)'} "
        f"(backend: `{source or 'unknown'}`)",
    ]
    if authors:
        prov_lines.append("- **Authors (candidate, unverified):**")
        for a in authors:
            prov_lines.append(f"  - {a}")
    else:
        prov_lines.append(
            "- **Authors (candidate, unverified):** "
            "(none returned by backend; TODO_verify)"
        )
    if topic_tags:
        prov_lines.append(
            f"- **Discovery topic tags:** {', '.join(topic_tags)}"
        )
    prov_lines.append(f"- **Discovery query:** {query or '(unknown)'}")
    prov_lines.append(f"- **Discovery backend:** {source or '(unknown)'}")
    prov_lines.append(
        f"- **Discovered at (UTC):** {discovered_at or '(unknown)'}"
    )
    prov_lines.append(
        f"- **Discovery dedupe id:** `{dedupe_id or '(unknown)'}`"
    )
    prov_lines.append(
        f"- **Discovery corpus_status:** `{corpus_status}`"
    )
    provenance_block = "\n".join(prov_lines)

    abstract_block = (
        f"> {abstract}"
        if abstract
        else "> (no abstract returned by the discovery backend; "
             "TODO_verify by fetching the paper directly)"
    )

    body = f"""{frontmatter}

{QUARANTINE_BANNER}

# {title}

> Draft scaffold compiled from a discovery candidate. Do not assert
> paper findings beyond the abstract below until the promotion gate at
> the bottom of this file is completed by a downstream evidence review.

## Candidate provenance (imported from discovery; unverified)

{provenance_block}

## Candidate abstract (imported verbatim from discovery backend)

{abstract_block}

## Layer 1 — Scientific invariant (TODO; do not invent)

Describe the load-bearing scientific claim the paper actually makes, as
stated in the paper itself. Quote or paraphrase only after the full text
has been read and the claim/evidence boundary is recorded in the
promotion gate. Until then, this section MUST be left as a TODO and the
draft remains non-authoritative.

- TODO: read the full text and extract the Layer-1 invariant.
- TODO: record the claim/evidence boundary (what the paper proves vs.
  what it merely paraphrases from prior work).

## Layer 2 — Executable protocol / capability contract (TODO)

- TODO: define data/tool contracts (instrument, cadence, level, archive).
- TODO: define the algorithm or workflow steps as composable units.
- TODO: define inputs/outputs of each step and the failure semantics.

## Layer 3 — Adapter / runtime binding (TODO)

- TODO: identify example adapter bindings (MCPs, dataset clients, harness
  affordances) that would satisfy the Layer-2 contract.
- TODO: record any environment or credential prerequisites.

## Layer 4 — Research-generation affordance (TODO)

- TODO: identify gaps, tensions, hypotheses, minimal experiments, and
  composable experiments this paper enables (do not fabricate; populate
  only after the full text has been read).

## Validation TODOs (promotion gate)

This draft will remain quarantined until every item below has been
completed and the corresponding flag in `metadata.yaml::promotion_gate`
has been flipped to `true`:

- [ ] verify DOI against the publisher of record
- [ ] verify arXiv id (matches the same paper as the DOI)
- [ ] verify title (round-trips against the publisher record)
- [ ] verify authors (full list, ordering, affiliations as needed)
- [ ] fetch full text and read past the abstract
- [ ] extract claim and evidence boundary (Layer 1)
- [ ] define data/tool contracts (Layer 2)
- [ ] record a numeric or figure-level validation target
- [ ] record failure modes and load-bearing assumptions
- [ ] assign a maturity tier consistent with `references/corpus_qa_report_v2.md`

## Provenance & quarantine notes

This file is a **non-authoritative** draft scaffold. The only content
imported from the discovery backend is the bibliographic provenance block
and the abstract above. Every other section is a TODO and must not be
treated as a paper finding. Do not promote into `references/corpus/`
without completing the promotion gate above.
"""
    return body


def render_metadata_yaml(record: Dict, *, slug: str) -> str:
    """Render the draft metadata.yaml (stdlib-only YAML emission)."""
    title = record.get("title") or ""
    year = record.get("year")
    doi = record.get("doi")
    arxiv_id = record.get("arxiv_id")
    bibcode = record.get("bibcode")
    url = record.get("url")
    source = record.get("source")
    query = record.get("query")
    discovered_at = record.get("discovered_at_utc")
    authors = _format_authors_list(record.get("authors"))
    topic_tags = record.get("topic_tags") or []
    corpus_status = record.get("corpus_status") or "unjoined"
    corpus_match_via = record.get("corpus_match_via")
