def _refuse_if_inside_corpus(drafts_dir: Path) -> None:
    """Hard rail: drafts may never land inside references/corpus/."""
    # Resolve as far as possible. The drafts-dir need not exist yet;
    # walk parents until we find one that does.
    candidate = drafts_dir
    probe = candidate
    while not probe.exists() and probe != probe.parent:
        probe = probe.parent
    try:
        resolved_probe = probe.resolve()
        corpus_resolved = CORPUS_DIR.resolve()
    except OSError as e:
        raise SystemExit(
            f"draft_paper_skill_from_candidates: cannot resolve drafts-dir: {e}"
        ) from None
    # Re-anchor the (possibly non-existent) tail back onto the resolved
    # probe so the check is robust to symlinks above the missing tail.
    tail = candidate.relative_to(probe) if probe in candidate.parents or probe == candidate else None
    resolved = resolved_probe / tail if tail is not None else resolved_probe

    if (
        resolved == corpus_resolved
        or corpus_resolved in resolved.parents
    ):
        raise SystemExit(
            "draft_paper_skill_from_candidates: refusing to write drafts "
            f"under references/corpus/ (got {drafts_dir}). Drafts are "
            "non-authoritative quarantine artifacts; the curated corpus "
            "is for verified entries only."
        )


def write_drafts(
    selected: Sequence[Dict],
    drafts_dir: Path,
    *,
    overwrite: bool = False,
) -> List[Dict]:
    """Write one ``<slug>/SKILL.md`` + ``<slug>/metadata.yaml`` per record."""
    drafts_dir.mkdir(parents=True, exist_ok=True)
    summaries: List[Dict] = []
    for rec in selected:
        slug = generate_slug(rec)
        draft_path = drafts_dir / slug
        if draft_path.exists():
            if not overwrite:
                raise SystemExit(
                    f"draft_paper_skill_from_candidates: draft directory "
                    f"already exists (use --overwrite to allow): {draft_path}"
                )
            shutil.rmtree(draft_path)
        draft_path.mkdir(parents=True)
        (draft_path / "SKILL.md").write_text(
            render_skill_md(rec, slug=slug), encoding="utf-8"
        )
        (draft_path / "metadata.yaml").write_text(
            render_metadata_yaml(rec, slug=slug), encoding="utf-8"
        )
        summaries.append(
            {
                "slug": slug,
                "path": str(draft_path.relative_to(drafts_dir)),
                "corpus_status": rec.get("corpus_status") or "unjoined",
                "dedupe_id": rec.get("id"),
                "title": rec.get("title"),
                "year": rec.get("year"),
                "doi": rec.get("doi"),
                "arxiv_id": rec.get("arxiv_id"),
                "source": rec.get("source"),
            }
        )
    return summaries


